/**
 * Helper: get product by ID
 */
export function getProductById(id) {
  return PRODUCTS.find((p) => p.id === id) || null;
}

/**
 * Helper: get product by slug
 */
export function getProductBySlug(slug) {
  return PRODUCTS.find((p) => p.slug === slug) || null;
}

/**
 * Helper: get featured products
 */
export function getFeaturedProducts() {
  return PRODUCTS.filter((p) => p.featured);
}

/**
 * Helper: get bestsellers
 */
export function getBestsellers() {
  return PRODUCTS.filter((p) => p.bestseller);
}

export const getBestSellerProducts = getBestsellers;

export function getNewProducts() {
  return [...PRODUCTS].slice(-8).reverse();
}

/**
 * Helper: get products by category
 */
export function getProductsByCategory(categorySlug) {
  return PRODUCTS.filter((p) => p.category === categorySlug);
}

export function getRelatedProducts(product, limit = 4) {
  if (!product) return [];
  return PRODUCTS
    .filter((item) => item.category === product.category && item.id !== product.id)
    .slice(0, limit);
}

/**
 * Helper: get discounted products
 */
export function getDiscountedProducts() {
  return PRODUCTS.filter((p) => p.salePrice && p.salePrice < p.price);
}
